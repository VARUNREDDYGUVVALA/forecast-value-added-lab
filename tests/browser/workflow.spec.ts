test('live lab advances, pauses and applies a new demand regime', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: 'Open live lab' }).click()
  await expect(page.getByRole('heading', { name: 'Live demand lab' })).toBeVisible()
  await page.getByLabel('Events per second').selectOption('100')
  await page.getByLabel('Demand regime').selectOption('Demand shift')
  await page.clock.runFor(1000)
  await expect(page.getByRole('cell', { name: 'Demand shift' }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const counter = page.locator('.stat').filter({ hasText: 'Events generated' })
  const previous = await counter.locator("strong").innerText()
  await page.clock.runFor(2000)
  await expect(counter.locator("strong")).toHaveText(previous)
  await page.getByRole('button', { name: 'Reset stream' }).click()
  await expect(counter).toContainText('0 of 600 retained')
})

